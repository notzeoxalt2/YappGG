const fs=require('fs'),path=require('path'),parser=require('@babel/parser'),traverse=require('@babel/traverse').default,generator=require('@babel/generator').default;
const root=path.resolve(__dirname,'..'),backup=path.join(root,'build/renderer-original');fs.mkdirSync(backup,{recursive:true});
for(const file of ['index.js','index.css'])if(!fs.existsSync(path.join(backup,file)))fs.copyFileSync(path.join(root,'ui',file),path.join(backup,file));
const source=fs.readFileSync(path.join(backup,'index.js'),'utf8'),ast=parser.parse(source);
let count;
traverse(ast,{ObjectProperty(property){if(property.node.key.value!==60555)return;
 const fn=property.get('value'),body=fn.get('body.body');
 const seed=body.find(p=>p.isExpressionStatement()&&generator(p.node).code.includes('globalThis.__originalMic ='));
 if(!seed)throw Error('Microphone exports were not found.');
 const needed=new Set(),queue=[];
 function references(p){p.traverse({ReferencedIdentifier(id){const binding=id.scope.getBinding(id.node.name);if(binding?.scope===fn.scope&&!needed.has(binding)){needed.add(binding);queue.push(binding);}}});}
 references(seed);for(const statement of body)if(!statement.isVariableDeclaration()&&!statement.isFunctionDeclaration())references(statement);
 while(queue.length)references(queue.shift().path);
 let removed=0;
 for(const statement of body){
  if(statement===seed)continue;
  if(statement.isVariableDeclaration()){
   for(const declaration of statement.get('declarations'))if(!needed.has(fn.scope.getBinding(declaration.node.id.name))){declaration.remove();removed++;}
   if(statement.node&&!statement.node.declarations.length)statement.remove();
  }else if(statement.isFunctionDeclaration()){if(!needed.has(fn.scope.getBinding(statement.node.id.name))){statement.remove();removed++;}}
 }
 count={removed,retained:needed.size};property.stop();
}});
fs.writeFileSync(path.join(root,'ui/index.js'),generator(ast,{compact:true}).code);
// General legacy controls precede the device-specific skin sections. Keep that
// original prefix and all font declarations; mic effect styles are generated by
// the original mic components and 954.css, both retained unchanged.
const css=fs.readFileSync(path.join(backup,'index.css'),'utf8'),cut=css.lastIndexOf('}',css.indexOf('#DeviceConfig'))+1;
const slim=css.slice(0,cut)+'\n'+[...css.matchAll(/@font-face\s*\{[^}]*\}/g)].map(m=>m[0]).join('\n');
fs.writeFileSync(path.join(root,'ui/mic-base.css'),slim);
const html=fs.readFileSync(path.join(root,'ui/index.html'),'utf8').replace(/href="index.css"/g,'href="mic-base.css"');
fs.writeFileSync(path.join(root,'ui/index.html'),html);
console.log(JSON.stringify({...count,entryBefore:source.length,entryAfter:fs.statSync(path.join(root,'ui/index.js')).size,cssBefore:css.length,cssAfter:slim.length}));
